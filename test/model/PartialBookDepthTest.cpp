#include <exchanges/binance/model/PartialBookDepth.h>
#include <rapidjson/document.h>
#include <gtest/gtest.h>

TEST(partialBookDepthTest, testDeserialize) {
    Binance::PartialBookDepthEvent event;
    const char* json = R"({"stream":"btcusdt@depth20","data":{"lastUpdateId":56052493002,"bids":[["99375.00000000","2.40608000"],["99374.95000000","0.00006000"],["99374.50000000","0.00024000"],["99374.29000000","0.00006000"],["99374.28000000","0.01005000"],["99374.08000000","0.00011000"],["99374.07000000","0.00006000"],["99373.88000000","0.00129000"],["99373.14000000","0.00011000"],["99373.08000000","0.00012000"],["99373.00000000","0.00010000"],["99372.61000000","0.00008000"],["99372.38000000","0.00015000"],["99372.13000000","0.00030000"],["99372.12000000","0.02827000"],["99372.01000000","0.00981000"],["99372.00000000","0.09510000"],["99371.80000000","0.00092000"],["99371.61000000","0.00008000"],["99371.42000000","0.00035000"]],"asks":[["99375.01000000","7.40574000"],["99375.15000000","0.00011000"],["99375.29000000","0.15114000"],["99375.62000000","0.14077000"],["99375.63000000","0.07669000"],["99375.91000000","0.27180000"],["99376.00000000","0.22631000"],["99376.35000000","0.07120000"],["99377.15000000","0.04000000"],["99377.84000000","0.00006000"],["99377.85000000","0.25138000"],["99379.07000000","0.00015000"],["99379.08000000","0.22835000"],["99379.82000000","0.14404000"],["99380.00000000","0.08861000"],["99380.49000000","0.00015000"],["99380.59000000","0.00006000"],["99381.27000000","0.05271000"],["99381.35000000","0.28410000"],["99381.36000000","0.32026000"]]}})";
    rapidjson::Document d;
    d.Parse(json);
    auto flag = event.deserialize(d);
    EXPECT_EQ(flag, true);
    EXPECT_EQ(event.stream, "btcusdt@depth20");
    EXPECT_EQ(event.lastUpdateId, 56052493002);
    EXPECT_EQ(event.bids.size(), 20);
    EXPECT_EQ(event.bids[0][0], "99375.00000000");
    EXPECT_EQ(event.bids[0][1], "2.40608000");
    EXPECT_EQ(event.asks.size(), 20);
    EXPECT_EQ(event.asks[0][0], "99375.01000000");
    EXPECT_EQ(event.asks[0][1], "7.40574000");
}
