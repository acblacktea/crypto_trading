#include <gtest/gtest.h>
#include <model/binance/MiniStatisticsTicker.hpp>
#include <rapidjson/document.h>

TEST(miniTickerEventEvent, testDeserialize)
{
    Binance::MiniStatisticsTickerEvent event;
    const char * json
        = R"({"stream":"btcusdt@miniTicker","data":{"e":"24hrMiniTicker","E":1733565885001,"s":"BTCUSDT","c":"99590.35000000","o":"97806.47000000","h":"101898.99000000","l":"97512.26000000","v":"33633.76740000","q":"3353672921.91293460"}})";
    rapidjson::Document d;
    d.Parse(json);
    auto flag = event.deserialize(d);
    EXPECT_EQ(flag, true);
    EXPECT_EQ(event.stream, "btcusdt@miniTicker");
    EXPECT_EQ(event.miniTicker.eventType, "24hrMiniTicker");
    EXPECT_EQ(event.miniTicker.eventTime, 1733565885001);
    EXPECT_EQ(event.miniTicker.symbol, "BTCUSDT");
    EXPECT_EQ(event.miniTicker.openPrice, "97806.47000000");
    EXPECT_EQ(event.miniTicker.closePrice, "99590.35000000");
    EXPECT_EQ(event.miniTicker.highPrice, "101898.99000000");
    EXPECT_EQ(event.miniTicker.lowPrice, "97512.26000000");
    EXPECT_EQ(event.miniTicker.baseAssetVolume, "33633.76740000");
    EXPECT_EQ(event.miniTicker.quoteAssetVolume, "3353672921.91293460");
}

